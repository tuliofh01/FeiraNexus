package crypto

import (
	"crypto/aes"
	"crypto/cipher"
	"crypto/rand"
	"encoding/hex"
	"errors"
	"fmt"
)

// ---------------------------------------------------------------------------
// AES-256-GCM authenticated encryption (envelope encryption for PII at rest)
// ---------------------------------------------------------------------------
//
// DIDACTIC — when to use this vs hashing:
//   HASHING (Argon2id)   : one-way. For secrets you must VERIFY but never
//                          read back (passwords). You cannot decrypt a hash.
//   ENCRYPTION (AES-GCM) : two-way. For data you must SHOW the user later
//                          (emails, addresses, phone numbers, API keys) while
//                          keeping it confidential in the DB/backup.
//
// WHY GCM (and not ECB/CBC?): GCM is AEAD — it encrypts AND authenticates.
// If an attacker tampers with the ciphertext, decryption FAILS instead of
// silently returning garbage (integrity + confidentiality in one primitive).
//
// NONCE RULE (the #1 GCM footgun): a GCM (key, nonce) pair must NEVER be
// reused — that leaks the authentication key and can reveal plaintext XORs.
// We generate a FRESH 12-byte random nonce for every encryption and prepend
// it to the output: output = nonce || ciphertext||tag.
//
// Key source: AES_MASTER_KEY_HEX (64 hex chars = 32 bytes = 256 bits) from
// .env, generated by scripts/gen_env.sh via `openssl rand -hex 32`.
//
// SUGGESTION: rotate the key periodically; since the nonce is random (not a
// counter), rotation is just "new key for new writes" + re-encrypt job.
// Consider envelope encryption (per-row data keys wrapped by a master key)
// when you move to KMS on DigitalOcean/AWS.

const (
	aesKeyLen   = 32   // AES-256
	gcmNonceLen = 12   // NIST-recommended nonce length for GCM
)

// AESEncrypter wraps a 256-bit key for encrypt/decrypt operations.
type AESEncrypter struct {
	gcm cipher.AEAD
}

// NewAESEncrypter parses the 64-char hex master key and pre-builds the GCM
// cipher (gcm.NewGCM is cheap but doing it once avoids per-call work).
func NewAESEncrypter(keyHex string) (*AESEncrypter, error) {
	key, err := hex.DecodeString(keyHex)
	if err != nil {
		return nil, fmt.Errorf("crypto: AES key is not valid hex: %w", err)
	}
	if len(key) != aesKeyLen {
		return nil, fmt.Errorf("crypto: AES key must be %d bytes, got %d", aesKeyLen, len(key))
	}
	block, err := aes.NewCipher(key)
	if err != nil {
		return nil, fmt.Errorf("crypto: creating AES cipher: %w", err)
	}
	gcm, err := cipher.NewGCM(block)
	if err != nil {
		return nil, fmt.Errorf("crypto: creating GCM: %w", err)
	}
	return &AESEncrypter{gcm: gcm}, nil
}

// Encrypt seals plaintext → nonce || ciphertext+tag (all base64-ready bytes).
func (a *AESEncrypter) Encrypt(plaintext []byte) ([]byte, error) {
	if len(plaintext) == 0 {
		return nil, errors.New("crypto: empty plaintext")
	}
	nonce := make([]byte, gcmNonceLen)
	if _, err := rand.Read(nonce); err != nil { // fresh CSPRNG nonce per call
		return nil, fmt.Errorf("crypto: generating nonce: %w", err)
	}
	// Seal appends ciphertext+tag to dst (the nonce here).
	return a.gcm.Seal(nonce, nonce, plaintext, nil), nil
}

// Decrypt opens nonce||ciphertext back to plaintext. Fails on ANY tampering.
func (a *AESEncrypter) Decrypt(data []byte) ([]byte, error) {
	if len(data) < gcmNonceLen {
		return nil, errors.New("crypto: ciphertext too short")
	}
	nonce, ciphertext := data[:gcmNonceLen], data[gcmNonceLen:]
	plaintext, err := a.gcm.Open(nil, nonce, ciphertext, nil)
	if err != nil {
		// Do NOT wrap with the raw error details in API responses — GCM
		// errors mean "forged/corrupt data"; log server-side instead.
		return nil, errors.New("crypto: decryption failed (tampered or wrong key)")
	}
	return plaintext, nil
}

// EncryptString / DecryptString are conveniences for text PII columns.
func (a *AESEncrypter) EncryptString(plain string) (string, error) {
	enc, err := a.Encrypt([]byte(plain))
	if err != nil {
		return "", err
	}
	return hex.EncodeToString(enc), nil // store as hex TEXT in the column
}

func (a *AESEncrypter) DecryptString(stored string) (string, error) {
	raw, err := hex.DecodeString(stored)
	if err != nil {
		return "", fmt.Errorf("crypto: decoding stored value: %w", err)
	}
	plain, err := a.Decrypt(raw)
	if err != nil {
		return "", err
	}
	return string(plain), nil
}

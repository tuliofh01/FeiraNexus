#!/usr/bin/env bash
# Generates ./fn_webserver/.env with CSPRNG secrets.
# Usage: ./scripts/gen_env.sh [--force]
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ENV_FILE="$(dirname "$SCRIPT_DIR")/.env"

FORCE=false
if [[ "${1:-}" == "--force" ]]; then
  FORCE=true
fi

if [[ -f "$ENV_FILE" && "$FORCE" == "false" ]]; then
  echo "[gen_env] $ENV_FILE already exists. Use --force to overwrite."
  exit 0
fi

if ! command -v openssl >/dev/null 2>&1; then
  echo "[gen_env] ERROR: openssl is required but not installed." >&2
  exit 1
fi

# 256-bit CSPRNG keys (64 hex chars = 32 bytes)
JWT_SECRET="$(openssl rand -hex 32)"
AES_MASTER_KEY_HEX="$(openssl rand -hex 32)"

cat > "$ENV_FILE" <<EOF
# FeiraNexus API environment (generated by scripts/gen_env.sh)
# Regenerate with: ./scripts/gen_env.sh --force

PORT=8080
GIN_MODE=debug

DATABASE_URL=postgres://feiranexus:feiranexus_dev_pass@localhost:5432/feiranexus_db?sslmode=disable

JWT_SECRET=${JWT_SECRET}
AES_MASTER_KEY_HEX=${AES_MASTER_KEY_HEX}

STRIPE_SECRET_KEY=sk_test_placeholder
STRIPE_WEBHOOK_SECRET=whsec_placeholder
EOF

chmod 600 "$ENV_FILE"
echo "[gen_env] Wrote $ENV_FILE (mode 600)."
